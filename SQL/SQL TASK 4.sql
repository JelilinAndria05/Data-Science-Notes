-- 1. Calculate the total sales amount for each order status.

SELECT
    O.status AS 'Order Status',
    SUM(OD.quantityOrdered * OD.priceEach) AS 'Total Sales Amount'
FROM 
	orders O
JOIN orderdetails OD
    ON O.orderNumber = OD.orderNumber
GROUP BY O.status;

-- 2. For each employee, find the number of unique orders handled, total quantity sold, and total sales amount.

SELECT
    E.employeeNumber AS 'Employee Number',
    COUNT(DISTINCT O.orderNumber) AS 'Number of Orders',
    SUM(OD.quantityOrdered) AS 'Total Quantity Sold',
    SUM(OD.quantityOrdered * OD.priceEach) AS 'Total Sales Amount'
FROM orderdetails OD
JOIN orders O
    ON OD.orderNumber = O.orderNumber
JOIN customers C
    ON O.customerNumber = C.customerNumber
JOIN employees E
    ON C.salesRepEmployeeNumber = E.employeeNumber
GROUP BY E.employeeNumber
ORDER BY SUM(OD.quantityOrdered * OD.priceEach) DESC;

-- 3. Calculate the average MSRP for each product line.

SELECT
