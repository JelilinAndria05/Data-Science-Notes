-- 1. Calculate the total quantity ordered, total sales amount, minimum and maximum selling prices, average selling price, and the number of unique orders.

SELECT
    SUM(quantityOrdered) AS 'No of Quantity',
    SUM(quantityOrdered * priceEach) AS 'Total Sales Amount',
    MIN(priceEach) AS 'Minimum Selling Price',
    MAX(priceEach) AS 'Maximum Selling Price',
    ROUND(AVG(priceEach), 2) AS 'Average Selling Price',
    COUNT(DISTINCT orderNumber) AS 'No of Orders'
FROM 
	orderdetails;

-- 2. Find the total quantity sold for each product line.

SELECT
    P.productLine AS 'Product Line',
    SUM(OD.quantityOrdered) AS 'Total Quantity Sold'
FROM 
	products P
JOIN orderdetails OD
    ON P.productCode = OD.productCode
GROUP BY P.productLine;

-- 3. Summarize each employee’s order count, quantity sold, and sales amount, including minimum, maximum, and average amounts. Sort by total sales in descending order.

SELECT
    E.employeeNumber AS 'Employee Number',
    COUNT(DISTINCT O.orderNumber) AS 'No of Orders',
    SUM(OD.quantityOrdered) AS 'Total Quantity Sold',
    SUM(OD.quantityOrdered * OD.priceEach) AS 'Total Sales Amount',
    MIN(OD.quantityOrdered * OD.priceEach) AS 'Minimum Amount',
    MAX(OD.quantityOrdered * OD.priceEach) AS 'Maximum Amount',
    ROUND(AVG(OD.quantityOrdered * OD.priceEach), 2) AS 'Average Amount'
FROM 
	orderdetails OD
JOIN orders O
    ON OD.orderNumber = O.orderNumber
JOIN customers C
    ON O.customerNumber = C.customerNumber
JOIN employees E
    ON C.salesRepEmployeeNumber = E.employeeNumber
GROUP BY E.employeeNumber
ORDER BY SUM(OD.quantityOrdered * OD.priceEach) DESC;

-- > Frame 3 problem statements using aggregate functions with WHERE conditions

-- 1. Find the total sales amount for orders with a status of Shipped

SELECT 
    SUM(quantityOrdered * priceEach) AS 'Amount'
FROM 
	orderdetails OD 
JOIN orders O
	ON OD.orderNumber = O.orderNumber
WHERE status = 'Shipped';

-- 2. Count the products with stock below 100 in each product line.

SELECT
    productLine AS 'Product Line',
    productCode AS 'Product Code',
    productName AS 'Product Name',
    quantityInStock AS 'Quantity in Stock'
FROM 
	products
WHERE quantityInStock < 100
ORDER BY productLine, quantityInStock;

